const entries = [];
for (const [key, file] of Object.entries(icons)) {
  // Some icon files are aliases (e.g. building-2 → building-complex); follow them.
  let path = `node_modules/lucide-react/dist/esm/icons/${file}.mjs`;
  let source = readFileSync(path, "utf8");
  const alias = source.match(/export \{ default \} from '\.\/([a-z0-9-]+)\.mjs'/);
  if (alias) {
    path = `node_modules/lucide-react/dist/esm/icons/${alias[1]}.mjs`;
    source = readFileSync(path, "utf8");
  }
  const { __iconData } = await import(pathToFileURL(path).href);
  const nodes = __iconData.node.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
  entries.push(`  ${JSON.stringify(key)}: ${JSON.stringify(nodes)},`);
}

const out = `// Generated by scripts/generate-icons.mjs from lucide-react (ISC License,
// https://lucide.dev). Do not edit by hand; add icons to the script instead.

export type IconNode = [tag: string, attrs: Record<string, string | number>][];

export const iconData = {
${entries.join("\n")}
} satisfies Record<string, IconNode>;
`;
writeFileSync("src/components/ui/icon-data.ts", out);
process.stdout.write(`wrote ${entries.length} icons${String.fromCharCode(10)}`);
